"""Shared helpers for experiments: data loading, result files, figure style, LaTeX tables."""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np
import numpy.typing as npt

from nnp.config import (
    FIGURES_DIR,
    GENERATED_TEX_DIR,
    RESULTS_DIR,
    TRAIN_DIR,
    VALIDATION_DIR,
    VALIDATION_LABELS,
)
from nnp.data import TrainingSet, load_ground_truth, load_samples, load_training

FloatArray = npt.NDArray[np.float64]
IntArray = npt.NDArray[np.int64]

# Reference categorical palette (dataviz skill, light mode), fixed order — never cycled.
SERIES = ("#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#6250d6", "#e34948")
TEXT = "#0b0b0b"
TEXT_SECONDARY = "#52514e"
GRID = "#e4e3df"
SEQUENTIAL = "Blues"


@dataclass(frozen=True)
class Data:
    train: TrainingSet
    X_val: FloatArray
    y_val: IntArray


def load_data() -> Data:
    train = load_training(TRAIN_DIR)
    _, X_val = load_samples(VALIDATION_DIR)
    y_val = load_ground_truth(VALIDATION_LABELS)
    if X_val.shape[0] != y_val.shape[0]:
        raise ValueError("validation samples and labels differ in length")
    return Data(train, X_val, y_val)


def _jsonable(o: Any) -> Any:
    if isinstance(o, np.generic):
        return o.item()
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, Path):
        return str(o)
    if isinstance(o, tuple):
        return list(o)
    raise TypeError(f"not JSON serializable: {type(o)}")


def save_json(name: str, payload: dict[str, Any]) -> Path:
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    path = RESULTS_DIR / f"{name}.json"
    path.write_text(json.dumps(payload, indent=2, default=_jsonable) + "\n")
    return path


def load_json(name: str) -> dict[str, Any]:
    data: dict[str, Any] = json.loads((RESULTS_DIR / f"{name}.json").read_text())
    return data


def figure(width: float = 6.0, height: float = 3.2) -> tuple[Any, Any]:
    """A matplotlib figure with the report's recessive axes style."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update(
        {
            "font.size": 9,
            "axes.edgecolor": GRID,
            "axes.labelcolor": TEXT_SECONDARY,
            "axes.titlesize": 10,
            "axes.titlecolor": TEXT,
            "xtick.color": TEXT_SECONDARY,
            "ytick.color": TEXT_SECONDARY,
            "axes.grid": True,
            "grid.color": GRID,
            "grid.linewidth": 0.6,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "legend.frameon": False,
            "savefig.bbox": "tight",
            "savefig.dpi": 200,
        }
    )
    fig, ax = plt.subplots(figsize=(width, height))
    ax.set_axisbelow(True)
    return fig, ax


def save_figure(fig: Any, name: str) -> Path:
    import matplotlib.pyplot as plt

    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    path = FIGURES_DIR / f"{name}.pdf"
    fig.savefig(path)
    fig.savefig(FIGURES_DIR / f"{name}.png")
    plt.close(fig)
    return path


def latex_table(
    name: str,
    header: list[str],
    rows: list[list[str]],
    caption: str,
    label: str,
    align: str | None = None,
    wide: bool = False,
) -> Path:
    """Write a booktabs table to ``report/generated/<name>.tex`` (\\input by the report).

    ``wide=True`` uses ``table*`` so the table spans both columns of a two-column layout.
    """
    env = "table*" if wide else "table"
    GENERATED_TEX_DIR.mkdir(parents=True, exist_ok=True)
    align = align or ("l" + "r" * (len(header) - 1))
    lines = [
        "% GENERATED by `uv run poe experiments` — do not edit by hand.",
        f"\\begin{{{env}}}[t]",
        "\\centering",
        "\\small",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        f"\\begin{{tabular}}{{{align}}}",
        "\\toprule",
        " & ".join(header) + " \\\\",
        "\\midrule",
        *[" & ".join(r) + " \\\\" for r in rows],
        "\\bottomrule",
        "\\end{tabular}",
        f"\\end{{{env}}}",
    ]
    path = GENERATED_TEX_DIR / f"{name}.tex"
    path.write_text("\n".join(lines) + "\n")
    return path


def latex_macros(values: dict[str, str]) -> Path:
    """Write ``\\newcommand`` macros (e.g. ``\\ValAcc``) so report numbers never go stale."""
    GENERATED_TEX_DIR.mkdir(parents=True, exist_ok=True)
    path = GENERATED_TEX_DIR / "macros.tex"
    existing: dict[str, str] = {}
    if path.exists():
        for line in path.read_text().splitlines():
            if line.startswith("\\newcommand{\\"):
                key = line[len("\\newcommand{\\") : line.index("}")]
                existing[key] = line[line.index("}{") + 2 : -1]
    existing.update(values)
    body = "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(existing.items()))
    path.write_text(
        "% GENERATED by `uv run poe experiments` — do not edit by hand.\n" + body + "\n"
    )
    return path


def pct(x: float, digits: int = 1) -> str:
    return f"{100 * x:.{digits}f}"
